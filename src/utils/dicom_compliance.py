#!/usr/bin/env python3
"""Copy a DICOM folder and fix selected compliance issues on copied files.

Module overview:
- Input: a folder containing top-level ``*.dcm`` files.
- Output: a copied folder where each DICOM is normalized according to
    deterministic compliance rules.
- Constraint: no new UID is generated by this module.

Main workflow:
1. Copy ``input_dir`` to ``output_dir``.
2. Iterate over each top-level DICOM file in ``output_dir``.
3. Apply metadata/sequence fixes in-place.
4. Save file only when at least one fix was applied.

Important constants:
- DICOM tags are defined as module constants (for example
    ``SERIES_INSTANCE_UID``, ``REFERENCED_SOP_INSTANCE_UID``).
- Sequence-level constraints are defined in
    ``EXPECTED_REFERENCED_SOP_CLASS_BY_SEQUENCE``.
- Required SOP Class UIDs for detached management sequences are stored in
    ``DETACHED_*`` constants.

The script is deterministic and never generates new UID values. It only:
- reuses existing valid UIDs already present in the object context, and/or
- repairs UID syntax when possible (for example, leading zero cleanup).

Fixes implemented:
1) (0020,000E) Series Instance UID invalid syntax:
    - repair existing UID syntax without generating a new UID.

2) (0028,0034) Pixel Aspect Ratio in Icon Image Sequence:
    - remove from all items of (0088,0200).

3) (0018,0082) Inversion Time conditional presence:
    - remove when sequence is not identified as inversion recovery.

4) (7FE0,0010) Pixel Data in private sequence items:
    - recursively remove from private SQ items.

5) (0008,1150)/(0008,1155) Referenced SOP UIDs in sequence items:
    - fix empty/invalid values using existing context UIDs when possible,
    - enforce sequence-specific SOP Class UIDs for:
      * (0008,1110) Referenced Study Sequence -> Detached Study Management SOP Class,
      * (0008,1120) Referenced Patient Sequence -> Detached Patient Management SOP Class,
      * (0008,1125) Referenced Visit Sequence -> Detached Visit Management SOP Class,
    - avoid values equal/derived from root Study Instance UID in these sequences,
    - remove unrecoverable invalid items.

6) (0010,21C0) Pregnancy Status invalid value:
    - normalize value '0' to 4 (Unknown).

7) Coded sequence items (for example *CodeSequence):
    - enforce presence of at least one of (0008,0100)/(0008,0119)/(0008,0120),
    - enforce non-empty (0008,0104) Code Meaning (filled from existing code value when possible),
    - remove invalid/unrecoverable coded items,
    - remove coded sequences that become empty after cleanup.

8) (0010,1010) Patient's Age malformed syntax/length:
    - normalize to AS format ``NNNU`` (e.g. ``41`` -> ``041Y``) when reparable.

9) (0040,1001) Requested Procedure ID empty:
    - fill from Accession Number (0008,0050) or Study ID (0020,0010) when empty,
      so the element stays present and compliant with the mutual 1C condition
      between (0040,1001) and (0032,1060) Requested Procedure Description.

10) Private Creator duplication in same private group:
    - remove duplicate private creator elements when same identifier appears
      more than once in one dataset/group.

11) (0040,9210) LUT Label wrong VR/VM:
        - rewrite element as SH VM=1 with best-effort text extraction from
            existing value.

12) (0040,9096) Real World Value Mapping Sequence – missing required elements:
        - fill LUT Label (0040,9210) when absent: ``LINEAR`` when slope/intercept
            present, ``TABULAR`` when LUT data present, otherwise ``LABEL``.
        - fill LUT Explanation (0028,3003) when absent with a descriptive default
            derived from the private Philips tag or the mapping type.
        - fill Measurement Units Code Sequence (0040,08EA) when absent with a
            dimensionless UCUM item (code ``1``, scheme ``UCUM``, meaning
            ``no units``).
        - fill Real World Value First/Last Value Mapped (0040,9216)/(0040,9211)
            when absent and LUT Data is not present: range [0, 2^BitsStored-1]
            derived from root dataset BitsStored (0028,0101), defaulting to 65535.
"""

